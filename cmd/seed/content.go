// textError is a recognition error put into an item's content: at rune
// position Position the text says Wrong instead of Correct.
type textError struct {
	Position int
	Wrong    string
	Correct  string
}

// Typical recognition errors, as one-letter substitutions (correct -> read):
// Kazakh-specific letters read as the plain Cyrillic letter, and Braille cells
// read as their mirror image (е dots 1-5 / и dots 2-4, д 1-4-5 / ф 1-2-4, ж 2-4-5 / х 1-2-5).
var confusions = map[domain.Language]map[rune]rune{
	domain.LangKazakh: {
		'қ': 'к', 'ә': 'а', 'ө': 'о', 'ү': 'у', 'ұ': 'у', 'і': 'и', 'ғ': 'г', 'ң': 'н',
		'е': 'и', 'д': 'ф', 'ж': 'х',
	},
	domain.LangRussian: {
		'е': 'и', 'и': 'е', 'д': 'ф', 'ф': 'д', 'ж': 'х', 'х': 'ж',
	},
}

// makeContent returns 3-6 paragraphs (separated by a blank line) of sentences
// that fit the category, with a few recognition errors when the accuracy is low.
// It uses its own random generator so the rest of the seed data does not change.
func makeContent(r *gofakeit.Faker, category domain.Category, lang domain.Language, accuracy float64) (string, []textError) {
	pool := sentences[category][lang]
	var order []string
	next := func() string {
		if len(order) == 0 {
			order = slices.Clone(pool)
			r.ShuffleAnySlice(order)
		}
		s := order[0]
		order = order[1:]
		return s
	}

	paragraphs := make([]string, r.Number(3, 6))
	for i := range paragraphs {
		parts := make([]string, r.Number(2, 4))
		for j := range parts {
			parts[j] = next()
		}
		paragraphs[i] = strings.Join(parts, " ")
	}
	text := []rune(strings.Join(paragraphs, "\n\n"))

	// Below 95% accuracy: 1 error, plus one per 2.5 points less, at most 6.
	count := 0
	if accuracy < 0.95 {
		count = min(6, 1+int((0.95-accuracy)*40))
	}
	return applyErrors(r, text, confusions[lang], count)
}

// applyErrors replaces one letter in up to count different words that have a
// confusable letter. A substitution keeps the length, so positions stay valid.
func applyErrors(r *gofakeit.Faker, text []rune, table map[rune]rune, count int) (string, []textError) {
	type word struct{ start, end int }
	var candidates []word
	for i := 0; i < len(text); {
		if !unicode.IsLetter(text[i]) {
			i++
			continue
		}
		start := i
		for i < len(text) && (unicode.IsLetter(text[i]) || text[i] == '-') {
			i++
		}
		if i-start >= 4 && slices.ContainsFunc(text[start:i], func(c rune) bool { _, ok := table[c]; return ok }) {
			candidates = append(candidates, word{start, i})
		}
	}
	r.ShuffleAnySlice(candidates)

	var errs []textError
	for _, w := range candidates[:min(count, len(candidates))] {
		correct := string(text[w.start:w.end])
		var letters []int
		for i := w.start; i < w.end; i++ {
			if _, ok := table[text[i]]; ok {
				letters = append(letters, i)
			}
		}
		i := letters[r.IntN(len(letters))]
		text[i] = table[text[i]]
		errs = append(errs, textError{Position: w.start, Wrong: string(text[w.start:w.end]), Correct: correct})
	}
	slices.SortFunc(errs, func(a, b textError) int { return a.Position - b.Position })
	return string(text), errs
}

